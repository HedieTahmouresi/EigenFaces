"""Shared figure rendering for the experiment scripts.

Not an experiment itself -- the `exp_*.py` prefix marks those. This module
holds the grid/imshow/plot boilerplate that more than one experiment needs
(E3's reconstruction grid, E4's per-axis curves, and the two checkpoint
figures regenerated by `checkpoint_figures.py`), so it gets written once
instead of three times.

Every figure is written under `figures/` resolved from this file's location,
so scripts land their output in the right place regardless of the working
directory they are run from.
"""

from pathlib import Path

import matplotlib

matplotlib.use("Agg")  # scripts run headless; never pop a window

import matplotlib.pyplot as plt  # noqa: E402  (must follow the backend call)
import numpy as np  # noqa: E402

from src.data import IMAGE_SHAPE  # noqa: E402

FIGURES_DIR = Path(__file__).resolve().parent.parent / "figures"


def as_images(X):
    """(n, 4096) flat vectors -> (n, 64, 64) images. Passes images through."""
    X = np.asarray(X, dtype=np.float64)
    if X.ndim == 1:
        X = X[None, :]
    if X.ndim == 3:
        return X
    return X.reshape(X.shape[0], *IMAGE_SHAPE)


def image_grid(
    images,
    titles=None,
    ncols=5,
    suptitle=None,
    row_labels=None,
    normalize="per_image",
    cmap="gray",
    panel_size=1.6,
):
    """Lay images out in a grid of imshow panels and return the figure.

    `normalize` controls the grey scale:

    - ``"per_image"`` -- each panel autoscales to its own min/max. Correct for
      eigenfaces, which are signed directions with no natural absolute scale;
      without it the low-variance ones render nearly flat grey.
    - ``"shared"`` -- one scale across every panel, so panels are comparable
      to each other. Correct for a reconstruction grid, where the point is
      that detail returns as k grows.
    - a ``(vmin, vmax)`` tuple -- a fixed scale, e.g. `data.PIXEL_RANGE`.

    `row_labels`, if given, names each row down the left-hand side (E3 uses
    it for the k of each row).
    """
    images = as_images(images)
    n = len(images)
    ncols = max(1, min(ncols, n))
    nrows = int(np.ceil(n / ncols))

    if normalize == "shared":
        vmin, vmax = float(images.min()), float(images.max())
    elif normalize == "per_image":
        vmin = vmax = None
    else:
        vmin, vmax = (float(v) for v in normalize)

    fig, axes = plt.subplots(
        nrows,
        ncols,
        figsize=(panel_size * ncols, panel_size * nrows + (0.6 if suptitle else 0.2)),
        squeeze=False,
    )

    for i, ax in enumerate(axes.ravel()):
        ax.set_xticks([])
        ax.set_yticks([])
        if i >= n:
            ax.set_axis_off()
            continue
        ax.imshow(images[i], cmap=cmap, vmin=vmin, vmax=vmax)
        if titles is not None and i < len(titles) and titles[i] is not None:
            ax.set_title(titles[i], fontsize=9)

    if row_labels is not None:
        for row, label in enumerate(row_labels):
            if row < nrows:
                axes[row][0].set_ylabel(label, fontsize=9)
                axes[row][0].set_axis_on()

    if suptitle:
        fig.suptitle(suptitle, fontsize=13)
    fig.tight_layout()
    return fig


def curves(
    x,
    series,
    xlabel,
    ylabel,
    suptitle=None,
    xscale=None,
    ylim=None,
    marker="o",
    baseline=None,
    figsize=(7.0, 4.5),
):
    """One or more y-series against a shared x axis; returns the figure.

    `series` maps a legend label to a sequence of y values. `baseline`, if
    given, maps a label to a horizontal reference line -- E2 draws E1's
    raw-pixel accuracy that way, since the whole claim is whether the curve
    reaches it.
    """
    fig, ax = plt.subplots(figsize=figsize)

    for label, y in series.items():
        ax.plot(x, y, marker=marker, label=label)

    if baseline:
        for label, value in baseline.items():
            ax.axhline(value, linestyle="--", linewidth=1.0, color="grey", label=label)

    ax.set_xlabel(xlabel)
    ax.set_ylabel(ylabel)
    if xscale:
        ax.set_xscale(xscale)
    if ylim:
        ax.set_ylim(*ylim)
    ax.grid(alpha=0.3)
    if len(series) > 1 or baseline:
        ax.legend()
    if suptitle:
        ax.set_title(suptitle)
    fig.tight_layout()
    return fig


def save(fig, filename):
    """Write `fig` into figures/ and return the path. Closes the figure."""
    FIGURES_DIR.mkdir(parents=True, exist_ok=True)
    path = FIGURES_DIR / filename
    fig.savefig(path, dpi=150, bbox_inches="tight")
    plt.close(fig)
    return path
